for (const cat of CATEGORIES) {
  const catData = ALL_MARKET_ASSETS[cat];
  if (!catData['Most active'] || catData['Most active'].length === 0) {
    catData['Most active'] = [...catData['Trending stocks']].reverse();
  }
  if (!catData['Top gainers'] || catData['Top gainers'].length === 0) {
    catData['Top gainers'] = [...catData['Trending stocks']].sort((a, b) => b.changePercent - a.changePercent);
  }
  if (!catData['Top losers'] || catData['Top losers'].length === 0) {
    catData['Top losers'] = [...catData['Trending stocks']].sort((a, b) => a.changePercent - b.changePercent);
  }
}
